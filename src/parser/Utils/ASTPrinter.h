#ifndef THESIS_COMPILER_ASTPRINTER_H
#define THESIS_COMPILER_ASTPRINTER_H

#include <iostream>
#include <memory>
#include <vector>
#include <thread>

#include "../expressions/AbstractExprAST.h"
#include "../expressions/keywordExpressions/BranchingIfExprAST.h"
#include "../expressions/keywordExpressions/LoopWhileExprAST.h"
#include "../expressions/operationExpressions/AssignmentExprAST.h"
#include "../expressions/operationExpressions/BinaryOperatorExprAST.h"
#include "../expressions/operationExpressions/DeclarationExprAST.h"
#include "../expressions/operationExpressions/FunctionPrintValueExprAST.h"
#include "../expressions/ProgramExprAST.h"
#include "../expressions/utilsExpressions/BlockExprAST.h"
#include "../expressions/valueExpressions/BooleanValueExprAST.h"
#include "../expressions/valueExpressions/FloatValueExprAST.h"
#include "../expressions/valueExpressions/IntegerValueExprAST.h"
#include "../expressions/valueExpressions/StringValueExprAST.h"
#include "../expressions/valueExpressions/VariableReferenceExprAST.h"


class ASTPrinter {
public:
    void printAST(const std::unique_ptr<ProgramExprAST> &programStatements);

private:
    void printIndent(int depth, bool isLastChild);

    void printFullProgram(const std::unique_ptr<ProgramExprAST> &program, int depth);

    void printAssignmentExpr(AssignmentExprAST *expr, int depth, bool isLastChild);
    void printBinaryOperatorExpr(BinaryOperatorExprAST *expr, int depth, bool isLastChild);
    void printBlockExpr(BlockExprAST *expr, int depth, bool isLastChild);
    void printBooleanValueExpr(BooleanValueExprAST *expr, int depth, bool isLastChild);
    void printBranchingIfExpr(BranchingIfExprAST *expr, int depth, bool isLastChild);
    void printDeclarationExpr(DeclarationExprAST *expr, int depth, bool isLastChild);
    void printExpression(const std::unique_ptr<AbstractExprAST> &expr, int depth, bool isLastChild);
    void printFloatValueExpr(FloatValueExprAST *expr, int depth, bool isLastChild);
    void printFunctionPrintValueExpr(FunctionPrintValueExprAST *expr, int depth, bool isLastChild);
    void printIntegerValueExpr(IntegerValueExprAST *expr, int depth, bool isLastChild);
    void printLoopWhileExpr(LoopWhileExprAST *expr, int depth, bool isLastChild);
    void printStringValueExpr(StringValueExprAST *expr, int depth, bool isLastChild);
    void printVariableReferenceExpr(VariableReferenceExprAST *expr, int depth, bool isLastChild);
};

#endif //THESIS_COMPILER_ASTPRINTER_H
